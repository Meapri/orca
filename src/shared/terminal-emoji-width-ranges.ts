export function isCodepointInRanges(codepoint: number, ranges: readonly CodepointRange[]): boolean {
  let low = 0
  let high = ranges.length - 1
  while (low <= high) {
    const mid = (low + high) >> 1
    const [first, last] = ranges[mid]
    if (codepoint < first) {
      high = mid - 1
    } else if (codepoint > last) {
      low = mid + 1
    } else {
      return true
    }
  }
  return false
}
